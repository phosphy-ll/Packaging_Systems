class Command(BaseCommand):
    help = "Добавляет разделы из утверждённых материалов и черновик оборудования, не перезаписывая изменения."

    def handle(self, *args, **options):
        for name, slug, order in CATEGORIES:
            Category.objects.get_or_create(slug=slug, defaults={"name": name, "sort_order": order})
        for slug, data in PAGES.items():
            Page.objects.get_or_create(slug=slug, defaults=data)

        category = Category.objects.get(slug="used-lines")
        product, created = Product.objects.get_or_create(
            title="Линия розлива Bertolaso 40.40.6",
            defaults={
                "slug": "liniya-rozliva-bertolaso-40-40-6",
                "category": category,
                "status": Product.Status.DRAFT,
                "condition": Product.Condition.USED,
                "availability": Product.Availability.REQUEST,
                "summary": (
                    "Комплектная линия для спокойных жидкостей. "
                    "Перед публикацией требуется сверить производительность."
                ),
                "description": (
                    "Данные из предоставленной презентации «Линия розлива 8 000 бут.»:\n"
                    "Триблок Bertolaso 40.40.6, 2006 г.; этикетировочная машина PE, 2004 г.; "
                    "коробоформовщик APSOL и укладчик APSOL, 2015 г.; "
                    "компрессор Atlas Copco и конвейерная система PROCONV-CHAIN.\n\n"
                    "В документах указана цена 110 000 EUR, условия EXW Incoterms 2020 (Казахстан). "
                    "Перед публикацией необходимо проверить актуальность цены и условий."
                ),
                "manufacturer": "Bertolaso",
                "model_name": "40.40.6",
                "production_year": 2006,
                "price": 110000,
                "currency": Product.Currency.EUR,
            },
        )
        if created:
            for order, (name, value) in enumerate([
                ("Производительность", "Требует проверки: в названии 8 000 бут/ч, для триблока указано 10 000 бут/ч"),
                ("Триблок", "Bertolaso 40.40.6, 2006 г."),
                ("Этикетировщик", "PE Универсал-Мастер, 2004 г., 16 столиков"),
                ("Коробоформовщик", "APSOL, 2015 г."),
                ("Укладчик коробов", "APSOL, 2015 г."),
                ("Компрессор", "Atlas Copco, 8,5 бар"),
                ("Конвейеры", "PROCONV-CHAIN"),
                ("Условия", "EXW Incoterms 2020, Казахстан"),
            ]):
                ProductSpecification.objects.create(product=product, name=name, value=value, sort_order=order)
        self.stdout.write(self.style.SUCCESS(
            "Разделы созданы при отсутствии. Черновик линии проверяйте перед публикацией."
        ))
